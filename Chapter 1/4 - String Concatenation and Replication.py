""" String Concatenation and Replication """

# When + is used to combine two str values.
# It joins the strings as the str concatenation operator.

conc1 = "Alice"  + "Bob"
print(conc1)

# When * is used to combine str values.
# It replicates a str against the int used.
# The * operator can only be used with one str and one int.

conc2 = "Bob" * 5
print(conc2)
